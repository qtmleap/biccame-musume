test('event_controls_have_exact_action_names', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto(`${fixture}?path=/events/`)
  const filter = page.getByRole('button', { name: 'イベントを絞り込む', exact: true })
  await filter.click()
  await expect(page.getByRole('dialog', { name: 'フィルター', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(filter).toBeFocused()
  const scheduleAction = page.getByRole('button', { name: '日程表示', exact: true })
  // A next-action command must not announce that the opposite view is pressed.
  await expect(scheduleAction).not.toHaveAttribute('aria-pressed', 'true')
  await scheduleAction.click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('event-view-mode'))).toBe(JSON.stringify('gantt'))
  const listAction = page.getByRole('button', { name: '一覧表示', exact: true })
  await expect(listAction).not.toHaveAttribute('aria-pressed', 'true')
  await listAction.click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('event-view-mode'))).toBe(JSON.stringify('grid'))
  await expect(page.getByRole('button', { name: '日程表示', exact: true })).toBeVisible()
})

test('mobile_region_and_month_expose_selected_state', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto(fixture)
  await expect(page.getByRole('radiogroup', { name: '地域で絞り込み', exact: true })).toBeVisible()
  await expect(page.getByRole('radio', { name: '全国', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: '北海道', exact: true }).click()
  await expect(page.getByRole('radio', { name: '北海道', exact: true })).toBeChecked()
  await expect(page.getByRole('radio', { name: '全国', exact: true })).not.toBeChecked()
  await expect(page.getByRole('button', { name: '10月に移動', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '11月に移動', exact: true }).click()
  await expect(page.getByRole('button', { name: '11月に移動', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: '10月に移動', exact: true })).toHaveAttribute('aria-pressed', 'false')
})
